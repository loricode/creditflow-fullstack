-- =====================================================================
-- CrediFlow · V1 · Esquema inicial
-- Solicitudes de crédito, tabla de amortización, outbox transaccional,
-- historial de estados (lo llena un trigger) e intentos de evaluación.
-- =====================================================================

CREATE TABLE solicitud_credito (
    id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    external_id         VARCHAR2(64)   NOT NULL,
    numero_documento    VARCHAR2(20)   NOT NULL,
    nombre_completo     VARCHAR2(150)  NOT NULL,
    email               VARCHAR2(150)  NOT NULL,
    ingresos_mensuales  NUMBER(15,2)   NOT NULL,
    gastos_mensuales    NUMBER(15,2)   NOT NULL,
    tipo_producto       VARCHAR2(20)   NOT NULL,
    monto               NUMBER(15,2)   NOT NULL,
    plazo_meses         NUMBER(3)      NOT NULL,
    estado              VARCHAR2(20)   DEFAULT 'RECIBIDA' NOT NULL,
    score               NUMBER(4),
    nivel_riesgo        VARCHAR2(10),
    tasa_anual          NUMBER(6,3),
    cuota_mensual       NUMBER(15,2),
    explicacion_ia      CLOB,
    proveedor_ia        VARCHAR2(30),
    referencia_core     VARCHAR2(40),
    s3_key              VARCHAR2(300),
    ultimo_error        VARCHAR2(1000),
    intentos            NUMBER(3)      DEFAULT 0 NOT NULL,
    version             NUMBER(10)     DEFAULT 0 NOT NULL,
    creado_en           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    evaluado_en         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_solicitud PRIMARY KEY (id),
    CONSTRAINT uq_solicitud_external UNIQUE (external_id),
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('RECIBIDA','EN_EVALUACION','APROBADA','RECHAZADA','ERROR')),
    CONSTRAINT ck_solicitud_producto CHECK (tipo_producto IN ('LIBRE_INVERSION','VEHICULO','VIVIENDA','EDUCACION')),
    CONSTRAINT ck_solicitud_riesgo CHECK (nivel_riesgo IS NULL OR nivel_riesgo IN ('BAJO','MEDIO','ALTO')),
    CONSTRAINT ck_solicitud_montos CHECK (monto > 0 AND ingresos_mensuales > 0 AND gastos_mensuales >= 0),
    CONSTRAINT ck_solicitud_plazo CHECK (plazo_meses BETWEEN 6 AND 360)
);

-- Listado del panel: filtro por estado ordenado por fecha
CREATE INDEX ix_solicitud_estado_fecha ON solicitud_credito (estado, creado_en DESC);
CREATE INDEX ix_solicitud_documento ON solicitud_credito (numero_documento);
CREATE INDEX ix_solicitud_producto ON solicitud_credito (tipo_producto);

COMMENT ON TABLE solicitud_credito IS 'Solicitud de crédito y su resultado de evaluación';
COMMENT ON COLUMN solicitud_credito.external_id IS 'Clave de idempotencia enviada por el cliente';
COMMENT ON COLUMN solicitud_credito.tasa_anual IS 'Tasa efectiva anual en porcentaje';

CREATE TABLE amortizacion (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    solicitud_id   NUMBER        NOT NULL,
    numero_cuota   NUMBER(3)     NOT NULL,
    fecha_pago     DATE          NOT NULL,
    cuota          NUMBER(15,2)  NOT NULL,
    capital        NUMBER(15,2)  NOT NULL,
    interes        NUMBER(15,2)  NOT NULL,
    saldo          NUMBER(15,2)  NOT NULL,
    CONSTRAINT pk_amortizacion PRIMARY KEY (id),
    CONSTRAINT fk_amortizacion_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud_credito (id) ON DELETE CASCADE,
    CONSTRAINT uq_amortizacion_cuota UNIQUE (solicitud_id, numero_cuota)
);

CREATE TABLE outbox_evento (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    agregado_id    NUMBER         NOT NULL,
    tipo           VARCHAR2(60)   NOT NULL,
    payload        CLOB           NOT NULL,
    estado         VARCHAR2(15)   DEFAULT 'PENDIENTE' NOT NULL,
    intentos       NUMBER(3)      DEFAULT 0 NOT NULL,
    ultimo_error   VARCHAR2(1000),
    creado_en      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    publicado_en   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_outbox PRIMARY KEY (id),
    CONSTRAINT ck_outbox_estado CHECK (estado IN ('PENDIENTE','PUBLICADO','FALLIDO')),
    CONSTRAINT ck_outbox_payload CHECK (payload IS JSON)
);

-- El publicador solo lee pendientes
CREATE INDEX ix_outbox_pendiente ON outbox_evento (estado, id);

CREATE TABLE solicitud_historial (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    solicitud_id     NUMBER        NOT NULL,
    estado_anterior  VARCHAR2(20),
    estado_nuevo     VARCHAR2(20)  NOT NULL,
    cambiado_en      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_historial PRIMARY KEY (id),
    CONSTRAINT fk_historial_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud_credito (id) ON DELETE CASCADE
);

CREATE INDEX ix_historial_solicitud ON solicitud_historial (solicitud_id, cambiado_en);

CREATE TABLE intento_evaluacion (
    id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    solicitud_id    NUMBER         NOT NULL,
    numero_intento  NUMBER(3)      NOT NULL,
    resultado       VARCHAR2(10)   NOT NULL,
    error           VARCHAR2(1000),
    duracion_ms     NUMBER(10)     NOT NULL,
    creado_en       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_intento PRIMARY KEY (id),
    CONSTRAINT fk_intento_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud_credito (id) ON DELETE CASCADE,
    CONSTRAINT ck_intento_resultado CHECK (resultado IN ('EXITO','FALLO'))
);

CREATE INDEX ix_intento_solicitud ON intento_evaluacion (solicitud_id, numero_intento);
